using System.Collections.Generic;

namespace FantaSim.App.World.Composition;

// Mantle x-ray view (M-A), task 3: marching cubes. Written fresh after the abandoned rewrite (the
// previous file was deleted mid-edit). Standard 256-case table approach (Lorensen–Cline via the
// canonical Bourke tables), with SPATIAL EDGE WELDING: every isosurface vertex lies on a lattice
// edge, and the vertex is created once per undirected lattice edge (keyed by the edge's lower
// lattice point + axis) and shared by all triangles referencing it — adjacent cells therefore share
// vertices exactly, which is what makes a closed scalar blob extract as a WATERTIGHT manifold
// (every undirected edge shared by exactly 2 triangles; asserted in tests).
//
// Pure, deterministic, Godot-free: cells are visited in a fixed z→y→x order, vertices are emitted
// in first-reference order, and the interpolation is a pure function of the two lattice samples.

/// <summary>
/// CPU marching cubes over a rectilinear scalar lattice. Extracts the isosurface of
/// <c>scalars &gt; isovalue</c> as an indexed triangle mesh with welded vertices in grid-index
/// space (positions in [0, N-1] per axis; callers map to world space).
/// </summary>
public static class MarchingCubes
{
    /// <summary>
    /// Extract the isosurface at <paramref name="isovalue"/>.
    /// </summary>
    /// <param name="scalars">Lattice values, index = (z * ny + y) * nx + x.</param>
    /// <param name="nx">Lattice points along X (>= 2).</param>
    /// <param name="ny">Lattice points along Y (>= 2).</param>
    /// <param name="nz">Lattice points along Z (>= 2).</param>
    /// <param name="isovalue">Surface level; the mesh bounds the region where the scalar exceeds it.</param>
    /// <param name="vertices">Welded vertex positions, flattened [x,y,z,...] in grid-index space.</param>
    /// <param name="triangles">Vertex indices, 3 per triangle.</param>
    public static void Extract(
        float[] scalars,
        int nx,
        int ny,
        int nz,
        float isovalue,
        out List<float> vertices,
        out List<int> triangles)
    {
        ArgumentNullException.ThrowIfNull(scalars);
        if (nx < 2 || ny < 2 || nz < 2)
            throw new ArgumentException("marching cubes requires at least 2 lattice points per axis.");
        if ((long)nx * ny * nz != scalars.Length)
            throw new ArgumentException("scalar array length must equal nx*ny*nz.", nameof(scalars));

        vertices = new List<float>();
        triangles = new List<int>();

        // Welded vertex per undirected lattice edge: key = (lattice point index) * 3 + axis.
        var edgeVertex = new Dictionary<long, int>();

        Span<float> val = stackalloc float[8];

        for (int z = 0; z < nz - 1; z++)
        for (int y = 0; y < ny - 1; y++)
        for (int x = 0; x < nx - 1; x++)
        {
            // Corner order matches the canonical tables (Bourke): 0..3 bottom ring (z), 4..7 top (z+1).
            val[0] = scalars[Idx(x, y, z, nx, ny)];
            val[1] = scalars[Idx(x + 1, y, z, nx, ny)];
            val[2] = scalars[Idx(x + 1, y + 1, z, nx, ny)];
            val[3] = scalars[Idx(x, y + 1, z, nx, ny)];
            val[4] = scalars[Idx(x, y, z + 1, nx, ny)];
            val[5] = scalars[Idx(x + 1, y, z + 1, nx, ny)];
            val[6] = scalars[Idx(x + 1, y + 1, z + 1, nx, ny)];
            val[7] = scalars[Idx(x, y + 1, z + 1, nx, ny)];

            int cubeIndex = 0;
            for (int i = 0; i < 8; i++)
            {
                if (val[i] > isovalue)
                    cubeIndex |= 1 << i;
            }

            if (cubeIndex == 0 || cubeIndex == 255)
                continue; // fully outside / fully inside: no surface in this cell

            int rowStart = cubeIndex * 16;
            for (int t = 0; TriTable[rowStart + t] != -1; t += 3)
            {
                int i0 = EdgeVertexIndex(TriTable[rowStart + t], x, y, z, val, isovalue, nx, ny, edgeVertex, vertices);
                int i1 = EdgeVertexIndex(TriTable[rowStart + t + 1], x, y, z, val, isovalue, nx, ny, edgeVertex, vertices);
                int i2 = EdgeVertexIndex(TriTable[rowStart + t + 2], x, y, z, val, isovalue, nx, ny, edgeVertex, vertices);

                // Degenerate (zero-area) triangles arise when a lattice value sits exactly on the
                // isovalue; dropping them keeps the edge-share count at exactly 2 (manifold).
                if (i0 == i1 || i1 == i2 || i2 == i0)
                    continue;

                triangles.Add(i0);
                triangles.Add(i1);
                triangles.Add(i2);
            }
        }
    }

    private static int Idx(int x, int y, int z, int nx, int ny) => (z * ny + y) * nx + x;

    /// <summary>Returns the welded vertex index for cube edge <paramref name="edge"/> of the cell at
    /// (x,y,z), creating (and interpolating) the vertex on first reference.</summary>
    private static int EdgeVertexIndex(
        int edge,
        int x,
        int y,
        int z,
        ReadOnlySpan<float> val,
        float isovalue,
        int nx,
        int ny,
        Dictionary<long, int> edgeVertex,
        List<float> vertices)
    {
        // Per cube edge: the two corner ids it connects, its canonical origin corner (the lower
        // lattice point of the undirected edge) and its axis (0=X, 1=Y, 2=Z).
        int cornerA = EdgeCornerA[edge];
        int cornerB = EdgeCornerB[edge];
        int origin = EdgeOriginCorner[edge];
        int axis = EdgeAxis[edge];

        int ox = x + CornerDx[origin];
        int oy = y + CornerDy[origin];
        int oz = z + CornerDz[origin];

        long key = ((long)Idx(ox, oy, oz, nx, ny)) * 3 + axis;
        if (edgeVertex.TryGetValue(key, out int existing))
            return existing;

        // Interpolate along the edge. Orient the interpolation from the canonical origin corner so
        // both adjacent cells compute the identical position (same two samples, same direction).
        float vA = val[cornerA];
        float vB = val[cornerB];
        bool originIsA = cornerA == origin;
        float vOrigin = originIsA ? vA : vB;
        float vOther = originIsA ? vB : vA;

        float denom = vOther - vOrigin;
        float tEdge = Math.Abs(denom) < 1e-12f ? 0.5f : (isovalue - vOrigin) / denom;
        if (tEdge < 0f) tEdge = 0f;
        else if (tEdge > 1f) tEdge = 1f;

        float px = ox, py = oy, pz = oz;
        switch (axis)
        {
            case 0: px += tEdge; break;
            case 1: py += tEdge; break;
            default: pz += tEdge; break;
        }

        int index = vertices.Count / 3;
        vertices.Add(px);
        vertices.Add(py);
        vertices.Add(pz);
        edgeVertex.Add(key, index);
        return index;
    }

